  /// Find country info by name (case-insensitive)
  static CountryInfo? findCountry(String? name) {
    if (name == null || name.trim().isEmpty) return null;
    final query = name.trim().toLowerCase();
    try {
      return countries.firstWhere(
        (c) => c.name.toLowerCase() == query || c.code.toLowerCase() == query,
      );
    } catch (_) {
      return null;
    }
  }

  /// Get predefined states for a country name, or empty list if none
  static List<String> getStatesForCountry(String? countryName) {
    final info = findCountry(countryName);
    return info?.states ?? const [];
  }
