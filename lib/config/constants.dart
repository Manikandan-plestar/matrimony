  /// Validates and normalizes human height input into standard format: X' Y" (Z cm)
  static String? normalizeHeight(String input) {
    final clean = input.trim();
    if (clean.isEmpty) return null;

    // Check if it already matches our predefined format
    for (final h in heightOptions) {
      if (h.toLowerCase() == clean.toLowerCase()) {
        return h;
      }
    }

    // Try parsing metric: e.g. "172 cm", "172cm", "172"
    final metricMatch = RegExp(r'^(\d{2,3})\s*(?:cm)?$', caseSensitive: false).firstMatch(clean);
    if (metricMatch != null) {
      final cm = int.tryParse(metricMatch.group(1)!);
      if (cm != null && cm >= 120 && cm <= 230) {
        final totalInches = (cm / 2.54).round();
        final feet = totalInches ~/ 12;
        final inches = totalInches % 12;
        return '$feet\' $inches" ($cm cm)';
      }
    }

    // Try parsing imperial: e.g. "5' 8\"", "5'8", "5ft 8in", "5 ft 8", "5.8"
    final imperialMatch = RegExp(r'''^(\d)['’ft\s]*\s*(\d{1,2})?["”in\s]*$''', caseSensitive: false).firstMatch(clean);
    if (imperialMatch != null) {
      final feet = int.tryParse(imperialMatch.group(1)!);
      final inches = int.tryParse(imperialMatch.group(2) ?? '0') ?? 0;
      if (feet != null && feet >= 4 && feet <= 7 && inches >= 0 && inches < 12) {
        final totalInches = (feet * 12) + inches;
        final cm = (totalInches * 2.54).round();
        if (cm >= 120 && cm <= 230) {
          return '$feet\' $inches" ($cm cm)';
        }
      }
    }

    return null;
  }

